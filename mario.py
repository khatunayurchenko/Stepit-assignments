while True:
    try:
        #მომხმარებლს ვთხოვ შეიყვანოს სასურველი სიმაღლე
        height = int(input("შეიყვანეთ პირამიდის სიმაღლე (1-დან 8-მდე): "))
        
        #ვამოწმებ, არის თუ არა რიცხვი 1-დან 8-ის ჩათვლით
        if 1 <= height <= 8:
            break
        else:
            print("არასწორი დიაპაზონი! გთხოვთ შეიყვანოთ რიცხვი 1-დან 8-მდე.")
    except ValueError:
        #ტექსტის ან არასწორი სიმბოლოს შეყვანის დამუშავება
        print("შეცდომა! გთხოვთ შეიყვანოთ მხოლოდ მთელი რიცხვი.")

#მთავარი ციკლი სტრიქონებისთვის (1-დან სიმაღლის ჩათვლით)
for i in range(1, height + 1):
    
    #შიდა ციკლი ჰარების (სპეისების) დასაბეჭდად
    for j in range(height - i):
        print(" ", end="")
        
    #შიდა ციკლი გისოსების (#) დასაბეჭდად
    for k in range(i):
        print("#", end="")
        
    #გადასვლა ახალ ხაზზე მიმდინარე სტრიქონის დასრულების შემდეგ
    print()